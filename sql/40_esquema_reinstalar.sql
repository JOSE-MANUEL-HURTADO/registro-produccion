-- ════════════════════════════════════════════════════════════════
--  ELÍPTICA · "Un solo SQL para revivir la app"
--  Pegar completo en Supabase → SQL Editor → New query → Run
--  Se puede correr más de una vez sin problema. Solo lee: no cambia datos.
-- ════════════════════════════════════════════════════════════════
--  Crea respaldo_esquema(): escribe, a partir de la base REAL, un único
--  SQL que reconstruye toda la app en un proyecto de Supabase nuevo:
--  tablas, llaves, vistas, funciones, triggers, permisos (RLS y grants),
--  la carpeta de PDF y el tiempo real. Como se genera de la base viva,
--  siempre está al día, incluso con cambios hechos a mano.
--  La copia diaria del Mac lo guarda como REINSTALAR_APP.sql.
--  También crea respaldo_usuarios(): correo e id de cada usuario (sin
--  contraseñas), para recrearlos con el mismo id al restaurar.
-- ════════════════════════════════════════════════════════════════

create or replace function public.respaldo_esquema()
returns text language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare
  o   text[] := array[]::text[];
  r   record;
  s   text;
  vistas_tipo oid[];
begin
  -- Desde la app: solo gerente o el usuario de respaldo. Desde el SQL Editor (sin usuario) también.
  if auth.uid() is not null and coalesce(public.rol_actual() in ('gerente','consulta'), false) is not true then
    raise exception 'Sin permiso';
  end if;

  o := o || format(E'-- ════════════════════════════════════════════════════════════════\n'
    '--  ELÍPTICA · REINSTALAR LA APP COMPLETA en un proyecto de Supabase NUEVO\n'
    '--  Generado automáticamente desde la base real: %s\n'
    '--  Pegar completo en Supabase → SQL Editor → Run (en un proyecto vacío).\n'
    '--  Después: cargar los datos de COPIA_COMPLETA_*.zip (ver LEEME.txt).\n'
    '-- ════════════════════════════════════════════════════════════════\n'
    'set check_function_bodies = off;\nset client_min_messages = warning;\n',
    to_char(now() at time zone 'America/Bogota', 'YYYY-MM-DD HH24:MI'));

  -- 1. Extensiones (las que no vienen por defecto)
  for r in select e.extname, n.nspname from pg_extension e join pg_namespace n on n.oid = e.extnamespace
            where e.extname not in ('plpgsql') order by 1 loop
    o := o || format(E'do $x$ begin create extension if not exists %I with schema %I; exception when others then raise warning %L, sqlerrm; end $x$;', r.extname, r.nspname, 'extension ' || r.extname || ': %');
  end loop;

  -- 2. Tipos propios (enum)
  for r in select t.typname, string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) lbl
             from pg_type t join pg_namespace n on n.oid = t.typnamespace join pg_enum e on e.enumtypid = t.oid
            where n.nspname = 'public' group by t.typname order by 1 loop
    o := o || format(E'do $x$ begin create type public.%I as enum (%s); exception when duplicate_object then null; end $x$;', r.typname, r.lbl);
  end loop;

  -- 3. Secuencias sueltas (no las de columnas identity)
  for r in select c.relname, sq.seqstart, sq.seqincrement
             from pg_class c join pg_namespace n on n.oid = c.relnamespace join pg_sequence sq on sq.seqrelid = c.oid
            where n.nspname = 'public' and c.relkind = 'S'
              and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
            order by 1 loop
    o := o || format('create sequence if not exists public.%I start %s increment %s;', r.relname, r.seqstart, r.seqincrement);
  end loop;

  -- 4. Tablas (columnas, not null, identity, generadas) + llave primaria y únicas
  o := o || E'\n-- ── Tablas ──'::text;
  for r in select c.oid, c.relname, c.relkind from pg_class c join pg_namespace n on n.oid = c.relnamespace
            where n.nspname = 'public' and c.relkind in ('r','p') order by c.oid loop
    select string_agg(
             format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
             || case when a.attidentity = 'a' then ' generated always as identity'
                     when a.attidentity = 'd' then ' generated by default as identity' else '' end
             || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored' else '' end
             || case when a.attnotnull then ' not null' else '' end,
             E',\n' order by a.attnum)
      into s
      from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
     where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped;
    o := o || format(E'create table if not exists public.%I (\n%s\n);', r.relname, coalesce(s, ''));
    for s in select format(E'do $x$ begin alter table public.%I add constraint %I %s; exception when invalid_table_definition or duplicate_table or duplicate_object then null; end $x$;', r.relname, k.conname, pg_get_constraintdef(k.oid))
               from pg_constraint k where k.conrelid = r.oid and k.contype in ('p','u') order by k.contype, k.conname loop
      o := o || s;
    end loop;
  end loop;

  -- 5. Secuencias: dueño de la columna
  for r in select c.relname seq, t.relname tab, a.attname col
             from pg_class c join pg_namespace n on n.oid = c.relnamespace
             join pg_depend d on d.objid = c.oid and d.deptype = 'a' and d.classid = 'pg_class'::regclass
             join pg_class t on t.oid = d.refobjid join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
            where n.nspname = 'public' and c.relkind = 'S' order by 1 loop
    o := o || format('alter sequence public.%I owned by public.%I.%I;', r.seq, r.tab, r.col);
  end loop;

  -- Tipos de fila de vistas: las funciones que los usan van después de las vistas
  select coalesce(array_agg(c.reltype), '{}') into vistas_tipo
    from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind in ('v','m');

  -- 6. Funciones (las que no dependen de vistas)
  o := o || E'\n-- ── Funciones ──'::text;
  for r in select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and p.prokind in ('f','p')
              and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
              and not (p.prorettype = any(vistas_tipo) or p.proargtypes::oid[] && vistas_tipo)
            order by p.oid loop
    o := o || (pg_get_functiondef(r.oid) || ';');
  end loop;

  -- 7. Valores por defecto, checks y llaves foráneas
  o := o || E'\n-- ── Valores por defecto y reglas ──'::text;
  for r in select c.relname, a.attname, pg_get_expr(d.adbin, d.adrelid) expr
             from pg_attrdef d join pg_class c on c.oid = d.adrelid join pg_namespace n on n.oid = c.relnamespace
             join pg_attribute a on a.attrelid = d.adrelid and a.attnum = d.adnum
            where n.nspname = 'public' and c.relkind in ('r','p') and a.attgenerated = '' and a.attidentity = ''
            order by c.oid, a.attnum loop
    o := o || format('alter table public.%I alter column %I set default %s;', r.relname, r.attname, r.expr);
  end loop;
  for r in select c.relname, k.conname, pg_get_constraintdef(k.oid) def, k.contype
             from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
            where n.nspname = 'public' and c.relkind in ('r','p') and k.contype in ('c','f','x')
            order by case k.contype when 'c' then 0 when 'x' then 1 else 2 end, c.oid, k.conname loop
    o := o || format(E'do $x$ begin alter table public.%I add constraint %I %s; exception when duplicate_object or duplicate_table then null; end $x$;',
                     r.relname, r.conname, r.def);
  end loop;

  -- 8. Índices (los que no son de una llave)
  for r in select pg_get_indexdef(i.indexrelid) def
             from pg_index i join pg_class c on c.oid = i.indrelid join pg_namespace n on n.oid = c.relnamespace
            where n.nspname = 'public' and c.relkind in ('r','p','m')
              and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)
            order by i.indexrelid loop
    o := o || (replace(r.def, 'CREATE INDEX ', 'CREATE INDEX IF NOT EXISTS ')
               || ';');
    o[array_length(o,1)] := replace(o[array_length(o,1)], 'CREATE UNIQUE INDEX ', 'CREATE UNIQUE INDEX IF NOT EXISTS ');
  end loop;

  -- 9. Vistas (en orden de dependencia)
  o := o || E'\n-- ── Vistas ──'::text;
  for r in
    with recursive v as (
      select c.oid, c.relname, c.relkind, c.reloptions from pg_class c join pg_namespace n on n.oid = c.relnamespace
       where n.nspname = 'public' and c.relkind in ('v','m')
    ), dep as (
      select distinct rw.ev_class vista, d.refobjid usa
        from pg_rewrite rw join pg_depend d on d.objid = rw.oid
       where rw.ev_class in (select oid from v) and d.refobjid in (select oid from v) and d.refobjid <> rw.ev_class
    ), prof as (
      select oid, 0 nivel from v
      union all
      select dep.vista, prof.nivel + 1 from prof join dep on dep.usa = prof.oid where prof.nivel < 50
    )
    select v.oid, v.relname, v.relkind, v.reloptions, max(prof.nivel) nivel
      from v join prof on prof.oid = v.oid group by v.oid, v.relname, v.relkind, v.reloptions order by 5, 1
  loop
    if r.relkind = 'v' then
      o := o || format(E'create or replace view public.%I%s as\n%s', r.relname,
                       case when r.reloptions is not null then ' with (' || array_to_string(r.reloptions, ', ') || ')' else '' end,
                       pg_get_viewdef(r.oid, true));
    else
      o := o || format(E'create materialized view if not exists public.%I as\n%s', r.relname, pg_get_viewdef(r.oid, true));
    end if;
  end loop;

  -- 10. Funciones que dependen de vistas
  for r in select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and p.prokind in ('f','p')
              and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
              and (p.prorettype = any(vistas_tipo) or p.proargtypes::oid[] && vistas_tipo)
            order by p.oid loop
    o := o || (pg_get_functiondef(r.oid) || ';');
  end loop;

  -- 11. Triggers (en tablas de la app y en auth.users si llaman funciones de la app)
  o := o || E'\n-- ── Triggers ──'::text;
  for r in select t.tgname, c.relname, n.nspname, pg_get_triggerdef(t.oid) def
             from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
             join pg_proc p on p.oid = t.tgfoid join pg_namespace pn on pn.oid = p.pronamespace
            where not t.tgisinternal and (n.nspname = 'public' or (n.nspname = 'auth' and pn.nspname = 'public'))
            order by n.nspname, c.relname, t.tgname loop
    o := o || format('drop trigger if exists %I on %I.%I;', r.tgname, r.nspname, r.relname) || (r.def || ';');
  end loop;

  -- 12. Seguridad por filas (RLS) y políticas
  o := o || E'\n-- ── Seguridad (RLS) ──'::text;
  for r in select c.relname, c.relrowsecurity, c.relforcerowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace
            where n.nspname = 'public' and c.relkind in ('r','p') and c.relrowsecurity order by 1 loop
    o := o || format('alter table public.%I enable row level security;', r.relname);
    if r.relforcerowsecurity then o := o || format('alter table public.%I force row level security;', r.relname); end if;
  end loop;
  for r in select * from pg_policies where schemaname in ('public','storage') order by schemaname, tablename, policyname loop
    o := o || format('drop policy if exists %I on %I.%I;', r.policyname, r.schemaname, r.tablename)
           || format('create policy %I on %I.%I as %s for %s to %s%s%s;',
                     r.policyname, r.schemaname, r.tablename, lower(r.permissive), lower(r.cmd),
                     (select string_agg(case when x = 'public' then 'public' else quote_ident(x) end, ', ') from unnest(r.roles) x),
                     case when r.qual is not null then ' using (' || r.qual || ')' else '' end,
                     case when r.with_check is not null then ' with check (' || r.with_check || ')' else '' end);
  end loop;

  -- 13. Permisos (grants) de tablas, vistas, secuencias y funciones
  o := o || E'\n-- ── Permisos ──'::text;
  for r in select c.oid, c.relname, c.relkind, c.relacl from pg_class c join pg_namespace n on n.oid = c.relnamespace
            where n.nspname = 'public' and c.relkind in ('r','p','v','m','S') order by c.relname loop
    o := o || format('revoke all on %s public.%I from public, anon, authenticated, service_role;',
                     case when r.relkind = 'S' then 'sequence' else 'table' end, r.relname);
    for s in select format('grant %s on %s public.%I to %s;', string_agg(lower(x.privilege_type), ', '),
                           case when r.relkind = 'S' then 'sequence' else 'table' end, r.relname,
                           case when x.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(x.grantee)) end)
               from aclexplode(coalesce(r.relacl, acldefault((case when r.relkind = 'S' then 's' else 'r' end)::"char", (select relowner from pg_class where oid = r.oid)))) x
              where x.grantee = 0 or pg_get_userbyid(x.grantee) in ('anon','authenticated','service_role')
              group by x.grantee loop
      o := o || s;
    end loop;
  end loop;
  for r in select p.oid, p.proacl, pg_get_function_identity_arguments(p.oid) args, p.proname, p.prokind
             from pg_proc p join pg_namespace n on n.oid = p.pronamespace
            where n.nspname = 'public' and p.prokind in ('f','p')
              and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
            order by p.proname, args loop
    o := o || format('revoke all on %s public.%I(%s) from public, anon, authenticated, service_role;',
                     case when r.prokind = 'p' then 'procedure' else 'function' end, r.proname, r.args);
    for s in select format('grant execute on %s public.%I(%s) to %s;', case when r.prokind = 'p' then 'procedure' else 'function' end,
                           r.proname, r.args, case when x.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(x.grantee)) end)
               from aclexplode(coalesce(r.proacl, acldefault('f'::"char", (select proowner from pg_proc where oid = r.oid)))) x
              where x.grantee = 0 or pg_get_userbyid(x.grantee) in ('anon','authenticated','service_role') loop
      o := o || s;
    end loop;
  end loop;

  -- 14. Carpetas de archivos (Storage), sin los archivos: los PDF están en PDF_OP
  if to_regclass('storage.buckets') is not null then
    o := o || E'\n-- ── Carpetas de archivos ──'::text;
    for r in execute 'select id, name, public, file_size_limit, allowed_mime_types from storage.buckets order by id' loop
      o := o || format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %s, %s) '
                       'on conflict (id) do update set public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;',
                       r.id, r.name, r.public, coalesce(r.file_size_limit::text, 'null'),
                       coalesce(quote_literal(r.allowed_mime_types::text) || '::text[]', 'null'));
    end loop;
  end if;

  -- 15. Tiempo real (la app escucha cambios de estas tablas)
  for r in select pt.tablename from pg_publication_tables pt
            where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public' order by 1 loop
    o := o || format(E'do $x$ begin alter publication supabase_realtime add table public.%I; exception when duplicate_object then null; end $x$;', r.tablename);
  end loop;

  -- 16. Contadores (consecutivos de remisión, ids): quedan en el valor que tenían
  for r in select ps.sequencename, ps.last_value from pg_sequences ps
            where ps.schemaname = 'public' and ps.last_value is not null order by 1 loop
    o := o || format('select setval(%L, %s, true);', 'public.' || quote_ident(r.sequencename), r.last_value);
  end loop;

  o := o || E'\nselect ''App reinstalada ✓ — ahora carga los datos de la copia'' as resultado;'::text;
  return array_to_string(o, E'\n') || E'\n';
end;
$$;

-- ── Para restaurar los datos en un proyecto nuevo ──
-- Carga un bloque de filas (el contenido de un .json de la copia) en una tabla.
-- Apaga los triggers de la tabla mientras carga, para no alterar los datos guardados.
create or replace function public.restaurar_tabla(p_tabla text, p_filas jsonb)
returns integer language plpgsql security definer set search_path = public as $$
declare
  v_rel  regclass;
  v_cols text;
  v_pk   text;
  v_upd  text;
  v_n    integer;
begin
  if auth.uid() is not null and coalesce(public.rol_actual() = 'gerente', false) is not true then
    raise exception 'Sin permiso';
  end if;
  select c.oid::regclass into v_rel from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r','p') and c.relname = p_tabla;
  if v_rel is null then raise exception 'Tabla no válida: %', p_tabla; end if;
  select string_agg(format('%I', a.attname), ', ' order by a.attnum) into v_cols
    from pg_attribute a where a.attrelid = v_rel and a.attnum > 0 and not a.attisdropped and a.attgenerated = '';
  -- Si la fila ya existe (p. ej. el perfil que se crea solo con el usuario), queda la de la copia
  select string_agg(format('%I', a.attname), ', ') into v_pk
    from pg_index i join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any(i.indkey::int2[])
   where i.indrelid = v_rel and i.indisprimary;
  select string_agg(format('%I = excluded.%I', a.attname, a.attname), ', ' order by a.attnum) into v_upd
    from pg_attribute a where a.attrelid = v_rel and a.attnum > 0 and not a.attisdropped and a.attgenerated = '' and a.attidentity <> 'a'
     and not exists (select 1 from pg_index i where i.indrelid = v_rel and i.indisprimary and a.attnum = any(i.indkey::int2[]));
  execute format('alter table %s disable trigger user', v_rel);
  execute format('insert into %s (%s) overriding system value select %s from jsonb_populate_recordset(null::%s, $1)%s',
                 v_rel, v_cols, v_cols, v_rel,
                 case when v_pk is null then ''
                      when v_upd is null then format(' on conflict (%s) do nothing', v_pk)
                      else format(' on conflict (%s) do update set %s', v_pk, v_upd) end) using p_filas;
  get diagnostics v_n = row_count;
  execute format('alter table %s enable trigger user', v_rel);
  return v_n;
end;
$$;

-- Al terminar de cargar: deja cada contador (consecutivos, ids) en el siguiente número libre
create or replace function public.restaurar_secuencias()
returns text language plpgsql security definer set search_path = public as $$
declare r record; v bigint; out text := '';
begin
  if auth.uid() is not null and coalesce(public.rol_actual() = 'gerente', false) is not true then
    raise exception 'Sin permiso';
  end if;
  for r in select s.oid::regclass seq, t.oid::regclass tab, a.attname col
             from pg_class s join pg_namespace n on n.oid = s.relnamespace
             join pg_depend d on d.objid = s.oid and d.deptype in ('a','i') and d.classid = 'pg_class'::regclass
             join pg_class t on t.oid = d.refobjid join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
            where n.nspname = 'public' and s.relkind = 'S'
           union   -- contadores usados como valor por defecto (p. ej. consecutivo de remisión)
           select s.oid::regclass, t.oid::regclass, a.attname
             from pg_attrdef ad join pg_depend d on d.classid = 'pg_attrdef'::regclass and d.objid = ad.oid and d.refclassid = 'pg_class'::regclass
             join pg_class s on s.oid = d.refobjid and s.relkind = 'S' join pg_namespace n on n.oid = s.relnamespace
             join pg_class t on t.oid = ad.adrelid join pg_attribute a on a.attrelid = t.oid and a.attnum = ad.adnum
            where n.nspname = 'public' loop
    execute format('select max(%I)::bigint from %s', r.col, r.tab) into v;
    v := greatest(v, (select ps.last_value from pg_sequences ps join pg_class c on c.relname = ps.sequencename join pg_namespace n on n.oid = c.relnamespace and n.nspname = ps.schemaname where c.oid = r.seq));
    if v is not null then perform setval(r.seq, v, true); out := out || r.seq || ' → ' || v || E'\n'; end if;
  end loop;
  return out;
end;
$$;
revoke all on function public.restaurar_tabla(text, jsonb) from public, anon;
revoke all on function public.restaurar_secuencias() from public, anon;
grant execute on function public.restaurar_tabla(text, jsonb) to authenticated;
grant execute on function public.restaurar_secuencias() to authenticated;

-- Lista de tablas para la copia, en el orden en que se deben restaurar
-- (primero las tablas de las que dependen otras). Reemplaza la del SQL 39.
create or replace function public.respaldo_tablas()
returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  if auth.uid() is not null and coalesce(public.rol_actual() in ('gerente','consulta'), false) is not true then
    raise exception 'Sin permiso';
  end if;
  return (
    with recursive t as (
      select c.oid, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
       where n.nspname = 'public' and c.relkind in ('r','p')
    ), fk as (
      select distinct k.conrelid hijo, k.confrelid padre from pg_constraint k
       where k.contype = 'f' and k.conrelid in (select oid from t) and k.confrelid in (select oid from t) and k.conrelid <> k.confrelid
    ), prof as (
      select oid, 0 nivel from t
      union all
      select fk.hijo, prof.nivel + 1 from prof join fk on fk.padre = prof.oid where prof.nivel < 50
    )
    select coalesce(jsonb_agg(relname order by nivel, relname), '[]'::jsonb)
      from (select t.relname, max(prof.nivel) nivel from t join prof on prof.oid = t.oid group by t.relname) x);
end;
$$;
revoke all on function public.respaldo_tablas() from public, anon;
grant execute on function public.respaldo_tablas() to authenticated;

-- Usuarios (solo id y correo; nunca contraseñas) para recrearlos con el mismo id
create or replace function public.respaldo_usuarios()
returns jsonb language plpgsql stable security definer set search_path = public, auth as $$
begin
  if auth.uid() is not null and coalesce(public.rol_actual() in ('gerente','consulta'), false) is not true then
    raise exception 'Sin permiso';
  end if;
  return (select coalesce(jsonb_agg(jsonb_build_object('id', u.id, 'email', u.email, 'created_at', u.created_at) order by u.created_at), '[]'::jsonb)
            from auth.users u);
end;
$$;

revoke all on function public.respaldo_esquema() from public, anon;
